<?php

declare(strict_types=1);

/*
 * Generează ifx_php.c: sursa PHP a stratului de compatibilitate, încorporată
 * în DLL ca un array de octeți. Rulează din directorul ifx_informix/:
 *
 *     php ifx_pdo_informix/generate-embedded.php
 */

$root = dirname(__DIR__) . '/php_informix';
$files = [
    'src/Informix/Config.php',
    'src/Informix/Error.php',
    'src/Informix/SqlType.php',
    'src/Informix/BlobHandle.php',
    'src/Informix/CharHandle.php',
    'src/Informix/SlobHandle.php',
    'src/Informix/HandleRegistry.php',
    'src/Informix/Connection.php',
    'src/Informix/Result.php',
    'src/Informix/Api.php',
];

$body = '';
$polyfill = file_get_contents($root . '/src/polyfill.php');
if ($polyfill === false) {
    fwrite(STDERR, "Nu pot citi php_informix/src/polyfill.php\n");
    exit(1);
}
$polyfill = preg_replace('/^\xEF\xBB\xBF/', '', $polyfill);
$polyfill = preg_replace('/^<\?php\s*/', '', $polyfill, 1);
$body .= "\n/* --- src/polyfill.php --- */\n" . rtrim($polyfill) . "\n";
$rename = [
    'Config' => 'IfxCompatConfig',
    'Error' => 'IfxCompatError',
    'SqlType' => 'IfxCompatSqlType',
    'BlobHandle' => 'IfxCompatBlobHandle',
    'CharHandle' => 'IfxCompatCharHandle',
    'SlobHandle' => 'IfxCompatSlobHandle',
    'HandleRegistry' => 'IfxCompatHandleRegistry',
    'Connection' => 'IfxCompatConnection',
    'Result' => 'IfxCompatResult',
    'Api' => 'IfxCompatApi',
];
foreach ($files as $file) {
    $code = file_get_contents($root . '/' . $file);
    if ($code === false) {
        fwrite(STDERR, "Nu pot citi {$file}\n");
        exit(1);
    }
    $code = preg_replace('/^\xEF\xBB\xBF/', '', $code);
    $code = preg_replace('/^<\?php\s*/', '', $code, 1);
    $code = preg_replace('/^\s*declare\s*\(\s*strict_types\s*=\s*1\s*\)\s*;\s*/m', '', $code, 1);
    $code = preg_replace('/^\s*namespace\s+Informix\s*;\s*/m', '', $code, 1);
    foreach ($rename as $from => $to) {
        $code = preg_replace('/\b' . preg_quote($from, '/') . '\b/', $to, $code);
    }
    $body .= "\n/* --- {$file} --- */\n" . rtrim($code) . "\n";
}

$bootstrap = $body . "\n";
$bytes = array_values(unpack('C*', $bootstrap));

$out = "/* Generated by ifx_pdo_informix/generate-embedded.php; do not edit. */\n";
$out .= "#include <stddef.h>\n\n";
$out .= "const unsigned char ifx_php_bootstrap[] = {\n";
$line = '   ';
foreach ($bytes as $i => $byte) {
    $line .= ' ' . $byte . ',';
    if (($i + 1) % 20 === 0) {
        $out .= $line . "\n";
        $line = '   ';
    }
}
if (trim($line) !== '') {
    $out .= $line . "\n";
}
$out .= "};\n";
$out .= 'const size_t ifx_php_bootstrap_len = ' . count($bytes) . ";\n";

file_put_contents(__DIR__ . '/ifx_php.c', $out);
printf("Scris ifx_php.c: %d bytes bootstrap, %d bytes C\n", strlen($bootstrap), strlen($out));
